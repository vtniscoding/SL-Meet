/**
 * Export Meeting Transcript Utility
 * Formats in-memory ASL translations, Speech captions & chat records and triggers browser download as a .txt file.
 */
export function downloadMeetingTranscript(arg1, arg2 = [], arg3 = []) {
  let roomId = 'Meeting';
  let transcriptLogs = [];
  let chatMessages = [];

  if (Array.isArray(arg1)) {
    transcriptLogs = arg1;
    roomId = typeof arg2 === 'string' ? arg2 : 'Meeting';
    chatMessages = Array.isArray(arg3) ? arg3 : [];
  } else {
    roomId = typeof arg1 === 'string' ? arg1 : 'Meeting';
    transcriptLogs = Array.isArray(arg2) ? arg2 : [];
    chatMessages = Array.isArray(arg3) ? arg3 : [];
  }

  const dateStr = new Date().toLocaleDateString();
  const timeStr = new Date().toLocaleTimeString();

  const header =
    `===================================================\n` +
    `📄 SL-MEET MEETING TRANSCRIPT & ACCESSIBILITY RECORD\n` +
    `Room ID: ${roomId}\n` +
    `Date: ${dateStr} | Time: ${timeStr}\n` +
    `===================================================\n\n`;

  // Sort & Merge ASL sentence logs, Speech captions, and text chat messages chronologically
  const combinedEntries = [
    ...transcriptLogs.map((log) => ({
      timestamp: log.timestamp || Date.now(),
      timeFormatted: log.time || new Date(log.timestamp || Date.now()).toLocaleTimeString(),
      sender: log.sender || 'Participant',
      type: log.type === 'SPEECH' ? 'Speech Caption' : log.type || 'ASL Translation',
      text: log.text,
    })),
    ...chatMessages
      .filter((msg) => msg.type !== 'system')
      .map((msg) => ({
        timestamp: msg.timestamp || Date.now(),
        timeFormatted: new Date(msg.timestamp || Date.now()).toLocaleTimeString(),
        sender: msg.senderName || 'Participant',
        type: 'Text Chat',
        text: msg.text,
      })),
  ].sort((a, b) => a.timestamp - b.timestamp);

  const body =
    combinedEntries.length === 0
      ? 'No ASL sentences, speech captions, or chat messages recorded in this call.\n'
      : combinedEntries
          .map((entry) => `[${entry.timeFormatted}] ${entry.sender} (${entry.type}): ${entry.text}`)
          .join('\n');

  const footer =
    `\n===================================================\n` +
    `Generated by SLMeet AI Platform (ASL & Speech AI)\n` +
    `===================================================\n`;

  const fullContent = header + body + footer;
  const blob = new Blob([fullContent], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);

  const link = document.createElement('a');
  link.href = url;
  link.download = `SLMeet-Transcript-${roomId}-${Date.now()}.txt`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
