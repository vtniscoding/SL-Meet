import { pipeline, env } from '@huggingface/transformers';
import { indexedDbCache } from '../services/modelCache';
import { STT_CONFIG } from '../config/sttConfig';

// Dedicated English Whisper model: onnx-community/whisper-base.en (~140MB quantized)
// Substantially higher acoustic fidelity and intrinsic resistance to noise hallucinations than tiny
const MODEL_NAME = STT_CONFIG.MODEL_NAME || 'onnx-community/whisper-base.en';

// Configure transformers.js environment for browser / electron
env.allowLocalModels = false;

// Attach custom IndexedDB cache to handle Electron file:// storage restrictions
try {
  env.useCustomCache = true;
  env.customCache = indexedDbCache;
} catch (cacheErr) {
  console.warn('[WhisperWorker] Custom cache initialization warning:', cacheErr);
}

// Configure WASM threads for optimal CPU performance
// Restrict threads to leave sufficient CPU headroom for MediaPipe and UI rendering
try {
  if (env.backends?.onnx?.wasm) {
    env.backends.onnx.wasm.proxy = false;
    const threads = Math.min(3, Math.max(1, (self.navigator?.hardwareConcurrency || 4) - 2));
    env.backends.onnx.wasm.numThreads = threads;
  }
} catch (wasmErr) {
  console.warn('[WhisperWorker] WASM thread configuration warning:', wasmErr);
}

let transcriber = null;
let isLoading = false;
let isProcessing = false;

// Asynchronous Request Queue to eliminate race conditions during model loading
const taskQueue = [];

// Deduplication cache to prevent repeating consecutive identical final captions within 3 seconds
let lastFinalText = '';
let lastFinalTime = 0;

/**
 * Structural Hallucination Guard:
 * Discards non-speech hallucination loops generated by acoustic noise.
 */
function looksLikeHallucination(text, durationSec) {
  if (!text || typeof text !== 'string') return true;
  const words = text.toLowerCase().match(/[\p{L}\p{N}']+/gu) || [];
  if (words.length === 0) return true;

  // Words per second check (speech rate boundary)
  const safeDuration = Math.max(0.5, durationSec);
  const wps = words.length / safeDuration;
  if (wps > 6.0) {
    if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Filtered out high WPS hallucination (${wps.toFixed(1)} wps): "${text}"`);
    return true; // Impossibly dense word burst
  }
  if (safeDuration > 3.0 && wps < 0.25) {
    if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Filtered out sparse hallucination (${wps.toFixed(2)} wps): "${text}"`);
    return true; // Faint noise triggering isolated hallucinated word over 3s
  }

  // Repetitive word ratio check (e.g. "you you you you you")
  if (words.length >= 4 && new Set(words).size / words.length < 0.45) {
    if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Filtered out repetitive loop: "${text}"`);
    return true;
  }

  // Consecutive identical word repeating 3+ times (e.g. "the the the")
  if (/(\b[\p{L}']+\b)(\s+\1){2,}/iu.test(text)) {
    if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Filtered out immediate word repeat: "${text}"`);
    return true;
  }

  return false;
}

function cleanTranscription(text, durationSec) {
  if (!text || typeof text !== 'string') return '';
  let cleaned = text.trim();

  // Strip bracketed and parenthesized non-speech tokens (e.g. [MUSIC], (Applause), [BLANK_AUDIO])
  cleaned = cleaned.replace(/\[.*?\]/g, '').replace(/\(.*?\)/g, '').trim();

  // Normalize for dictionary hallucination matching
  const normalized = cleaned.toLowerCase().replace(/[^\w\s]/g, '').trim();

  const hallucinations = new Set([
    'thank you',
    'thank you for watching',
    'thanks for watching',
    'thanks',
    'bye',
    'bye bye',
    'goodbye',
    'you',
    'so',
    'the',
    'a',
    'oh',
    'ah',
    'uh',
    'um',
    'subscribe',
    'subscribe to my channel',
    'subtitles by',
    'watching',
    'silence',
    'be seeing you',
    'see you next time',
    'please like and share',
  ]);

  if (hallucinations.has(normalized)) {
    if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Filtered exact hallucination match: "${cleaned}"`);
    return '';
  }

  // Common subtitle artifact regexes
  if (/(thanks? for watching|subscribe to my channel|subtitles by|be seeing you|see you next time|like and subscribe)/i.test(cleaned)) {
    if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Filtered regex hallucination pattern: "${cleaned}"`);
    return '';
  }

  // Structural sanity check
  if (looksLikeHallucination(cleaned, durationSec)) {
    return '';
  }

  // Discard isolated punctuation or 1-character outputs
  if (normalized.length <= 1) {
    return '';
  }

  return cleaned;
}

async function loadModel() {
  if (transcriber || isLoading) return;
  isLoading = true;

  self.postMessage({ type: 'status', status: 'loading' });

  try {
    console.log(`[WhisperWorker] Loading ${MODEL_NAME} using pure WASM CPU SIMD (INT8 Quantized)...`);
    transcriber = await pipeline('automatic-speech-recognition', MODEL_NAME, {
      device: 'wasm',
      dtype: {
        encoder_model: 'quantized',
        decoder_model_merged: 'quantized',
      },
      progress_callback: (info) => {
        self.postMessage({ type: 'progress', info });
      },
    });

    console.log(`[WhisperWorker] ${MODEL_NAME} successfully initialized and ready for inference.`);
    self.postMessage({ type: 'status', status: 'ready' });
  } catch (err) {
    console.error(`[WhisperWorker] Error loading ${MODEL_NAME}:`, err);
    self.postMessage({ type: 'error', error: err.message || 'Failed to load Whisper model' });
  } finally {
    isLoading = false;
  }
}

async function runInference(audio, isFinal, segmentId) {
  if (!transcriber) return;

  const durationSec = audio.length / 16000;
  const startTime = Date.now();

  try {
    // Highly optimized decoding parameters:
    // num_beams: 1 (greedy search) is lightning-fast on CPU, eliminates hallucination loops,
    // and produces pristine English subtitles when paired with whisper-base
    const result = await transcriber(audio, {
      sampling_rate: 16000,
      return_timestamps: false,
      num_beams: 1,
      no_repeat_ngram_size: 3,
    });

    const elapsedMs = Date.now() - startTime;
    const rawText = result && typeof result.text === 'string' ? result.text : '';
    const cleanedText = cleanTranscription(rawText, durationSec);

    if (cleanedText) {
      const now = Date.now();
      // 3-second deduplication for identical consecutive final captions
      if (isFinal && cleanedText === lastFinalText && now - lastFinalTime < 3000) {
        if (STT_CONFIG.DEBUG) console.log(`[WhisperWorker] Suppressed duplicate final caption: "${cleanedText}"`);
        return;
      }

      if (isFinal) {
        lastFinalText = cleanedText;
        lastFinalTime = now;
      }

      if (STT_CONFIG.DEBUG) {
        console.log(`[WhisperWorker] ${isFinal ? 'Final' : 'Interim'} (#${segmentId}, ${elapsedMs}ms):`, cleanedText);
      }

      self.postMessage({
        type: 'result',
        text: cleanedText,
        isFinal: !!isFinal,
        segmentId,
      });
    }
  } catch (err) {
    console.error('[WhisperWorker] Transcription error:', err);
  }
}

async function processQueue() {
  if (isProcessing || !transcriber) return;
  isProcessing = true;

  while (taskQueue.length > 0) {
    const task = taskQueue.shift();
    await runInference(task.audio, task.isFinal, task.segmentId);
  }

  isProcessing = false;
}

self.onmessage = async (e) => {
  const { type, audio, isFinal, segmentId } = e.data || {};

  if (type === 'load') {
    await loadModel();
    await processQueue();
  } else if (type === 'transcribe') {
    if (!audio) return;

    if (isFinal) {
      taskQueue.push({ audio, isFinal: true, segmentId });
    } else if (STT_CONFIG.ENABLE_INTERIM) {
      // Discard older queued interim if a newer one arrives
      const existingInterimIndex = taskQueue.findIndex((t) => !t.isFinal);
      if (existingInterimIndex >= 0) {
        taskQueue[existingInterimIndex] = { audio, isFinal: false, segmentId };
      } else {
        taskQueue.push({ audio, isFinal: false, segmentId });
      }
    }

    if (!transcriber && !isLoading) {
      loadModel().then(processQueue);
    } else if (transcriber) {
      processQueue();
    }
  }
};
